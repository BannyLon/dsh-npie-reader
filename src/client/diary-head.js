/**
 * 日记页顶部那一条「标题 + 一行事实」要不要有内容。
 *
 * ★★ 这条判据改过一次，方向是反的 —— 记在这里，别再改回去。
 *
 *   用户 2026-10-30 第一次：
 *     「私密日记这一页也改成与记录这一页格式统一显示，读后感里也全屏显示，
 *       不要有顶部的条」
 *   我读成「私密与读后感的顶栏都撤掉」，做出来了。第二次被纠正：
 *     「这个页面保持和之前一致，就是顶部有标题栏」（写读后感那一屏）
 *     「私密日记同样，这个页面和之前保持一致，只是增加的说明页没有标题栏」
 *
 *   ⇒ 要撤的不是**工作页**的顶栏，是**说明页**的顶栏。两者不是一回事：
 *     · 工作页（今天写了什么 / 写给哪本书）：顶栏就是这一页的抬头，要留 ——
 *       私密那条报「今天 · N 条 · M 字 · 本地加密」，读后感那条报
 *       「《书名》· 已读完 · N 条划线 · M 篇读后感」。撤掉之后页面没有标题。
 *     · 说明页（灵感开场「寸心拾遗」/ 读后感欢迎页「读完的书，值得留一句」）：
 *       上面一个可操作的对象都没有，顶上再挂一行「这是什么」，只是把下面那几段
 *       说明再说一遍 —— 那才是用户说的「顶部的条」。
 *
 * ★ 读后感必须按**有没有选书**分，不能按模块分：同一个模块里两个状态，
 *   没选书时右边是那张说明页，选了书才是写作页。顶栏跟着状态走。
 *
 * ★ 抽成纯函数而不是写在 JSX 的三元里：这条判据写反，界面上只是「少一行字」，
 *   看起来完全正常 —— 单测钉得住，肉眼钉不住。而且它已经写反过一次。
 *
 * @param {object} options
 * @param {boolean} options.cover  是否正停在灵感开场封面（「寸心拾遗 · 思想原点」）。
 * @param {string} options.module  当前模块（`inspiration` / `private` / `reflection`）。
 * @param {boolean} options.book   读后感模块里是否已经选中一本书（说明页 vs 写作页）。
 * @returns {boolean}
 */
export function headVisible({ cover, module, book }) {
  if (cover) return false;
  // 读后感的说明页（还没选书）：一个可写的对象都没有，顶上不留标题。
  if (module === 'reflection') return Boolean(book);
  return true;
}
